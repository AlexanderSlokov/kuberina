"""The adapter's one point of contact with PyYAML (AGENTS.md, Dependencies)."""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path

import yaml


def write_yaml_document(
    document: Mapping[str, object], path: Path, banner: str
) -> None:
    """Write one YAML document, keeping key order, under a `#` comment banner.

    Example:
        write_yaml_document(infra, Path("out/infra.yaml"), "Generated by bench/alibaba")
    """
    comment = "".join(f"# {line}\n" for line in banner.splitlines())
    body = yaml.safe_dump(
        dict(document), sort_keys=False, default_flow_style=None, width=100
    )
    path.write_text(comment + body, encoding="utf-8")


def read_yaml_document(path: Path) -> dict[str, object]:
    """Read one YAML document back as plain Python values.

    Example:
        workloads = read_yaml_document(Path("out/workloads.yaml"))
    """
    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        raise ValueError(
            f"{path} holds a {type(loaded).__name__}, expected a YAML mapping"
        )
    return loaded
