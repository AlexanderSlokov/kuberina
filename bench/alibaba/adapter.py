"""Convert the Alibaba GPU trace and FGD simulator logs into Kuberina IR (backlog X-2).

Run from `bench/`:

    python -m alibaba.adapter --nodes <node-csv> --pods <pod-csv> \
        --log FGD=<simon.log.gz> --log BestFit=<simon.log.gz> --out <dir>

It writes `infra.yaml`, `workloads.yaml`, and `sequence.csv` into `<dir>`. It writes
nothing unless every log offered the same pods and the trace demand matches each
logged `Arrived GPU Milli` total; after writing, it reads `workloads.yaml` back and
checks the total once more.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

from alibaba.demand_check import (
    check_arrived_demand,
    check_same_sequence,
    emitted_gpu_milli,
)
from alibaba.ir_documents import build_infrastructure, build_workloads
from alibaba.sequence import build_sequence_rows, write_sequence_csv
from alibaba.simulator_log import ArrivalRecord, read_simulator_log
from alibaba.trace_csv import TraceNode, TracePod, read_trace_nodes, read_trace_pods
from alibaba.yaml_io import read_yaml_document, write_yaml_document

RecordsByPolicy = Mapping[str, Sequence[ArrivalRecord]]


def main(argv: Sequence[str] | None = None) -> int:
    """Run the adapter; return 1 with a message naming the first failed check.

    Example:
        main(["--nodes", "nodes.csv", "--pods", "pods.csv", "--log", "FGD=simon.log", "--out", "out"])
    """
    args = _parse_arguments(argv)
    try:
        _convert(args.nodes, args.pods, _read_logs(args.log), args.out)
    except (ValueError, OSError) as error:
        print(f"alibaba adapter: {error}", file=sys.stderr)
        return 1
    return 0


def _parse_arguments(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="python -m alibaba.adapter", description=__doc__.splitlines()[0]
    )
    parser.add_argument(
        "--nodes", type=Path, required=True, help="openb_node_list_gpu_node.csv"
    )
    parser.add_argument(
        "--pods",
        type=Path,
        required=True,
        help="pod list, such as openb_pod_list_default.csv",
    )
    parser.add_argument(
        "--log",
        action="append",
        required=True,
        metavar="POLICY=PATH",
        help="simulator log of one policy; repeat per policy",
    )
    parser.add_argument("--out", type=Path, required=True, help="output directory")
    return parser.parse_args(argv)


def _read_logs(specs: Sequence[str]) -> dict[str, list[ArrivalRecord]]:
    records_by_policy: dict[str, list[ArrivalRecord]] = {}
    for spec in specs:
        policy, separator, path = spec.partition("=")
        if not separator or not policy or not path:
            raise ValueError(f"--log {spec!r} must have the shape POLICY=PATH")
        records_by_policy[policy] = read_simulator_log(Path(path))
    return records_by_policy


def _convert(
    nodes_csv: Path, pods_csv: Path, records_by_policy: RecordsByPolicy, out: Path
) -> None:
    nodes, pods = read_trace_nodes(nodes_csv), read_trace_pods(pods_csv)
    reference = next(iter(records_by_policy.values()))
    check_same_sequence(records_by_policy)
    check_arrived_demand(reference, pods)
    _write_outputs(
        nodes,
        pods,
        records_by_policy,
        out,
        _banner(nodes_csv, pods_csv, records_by_policy),
    )
    _check_written_demand(out / "workloads.yaml", reference[-1].arrived_gpu_milli)
    _report(len(nodes), reference, out)


def _write_outputs(
    nodes: Sequence[TraceNode],
    pods: Mapping[str, TracePod],
    records_by_policy: RecordsByPolicy,
    out: Path,
    banner: str,
) -> None:
    reference = next(iter(records_by_policy.values()))
    out.mkdir(parents=True, exist_ok=True)
    write_yaml_document(build_infrastructure(nodes), out / "infra.yaml", banner)
    write_yaml_document(
        build_workloads(reference, pods), out / "workloads.yaml", banner
    )
    with (out / "sequence.csv").open("w", newline="", encoding="utf-8") as stream:
        write_sequence_csv(build_sequence_rows(records_by_policy, pods), stream)


def _check_written_demand(workloads_path: Path, logged_milli: int) -> None:
    written = emitted_gpu_milli(read_yaml_document(workloads_path))  # type: ignore[arg-type]
    if written != logged_milli:
        raise ValueError(
            f"{workloads_path} holds {written} milli-GPU, the log says {logged_milli}"
        )


def _banner(nodes_csv: Path, pods_csv: Path, records_by_policy: RecordsByPolicy) -> str:
    logs = ", ".join(records_by_policy)
    return (
        "Generated by bench/alibaba/adapter.py (backlog X-2). Do not edit.\n"
        f"Trace: {nodes_csv.name}, {pods_csv.name}. Arrival order from the simulator log of: {logs}."
    )


def _report(node_count: int, reference: Sequence[ArrivalRecord], out: Path) -> None:
    print(f"nodes: {node_count}")
    print(f"pods: {len(reference)}")
    print(f"GPU demand written and logged: {reference[-1].arrived_gpu_milli} milli-GPU")
    print(
        f"wrote {out / 'infra.yaml'}, {out / 'workloads.yaml'}, {out / 'sequence.csv'}"
    )


if __name__ == "__main__":
    sys.exit(main())
