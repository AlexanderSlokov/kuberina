# WHY: 5 affinity chains create cascading dependencies that force the GA
# to co-locate entire stacks — exponentially harder than pairwise affinity.
AFFINITY_CHAINS: list[list[str]] = [
    ["web-frontend", "api-gateway", "redis-cache"],
    ["order-service", "payment-service", "postgres-primary"],
    ["mobile-bff", "auth-service", "vault"],
    ["llm-inference", "embedding-server", "feature-store"],
    ["prometheus", "grafana", "loki"],
]

# WHY: anti-affinity pairs across tiers create cross-cutting constraints
# that prevent the GA from simply partitioning by tier.
ANTI_AFFINITY_CROSS: list[tuple[str, str]] = [
    ("postgres-primary", "elasticsearch"),  # both heavy — separate them
    ("kafka-broker", "postgres-primary"),   # I/O isolation
    ("training-worker", "llm-inference"),   # GPU bandwidth contention
    ("api-gateway", "image-processor"),     # CPU contention
    ("redis-cache", "kafka-broker"),        # memory contention
]


def generate_workloads() -> dict:
    """Build the MSC Irina workload document in Kuberina IR v1 form.

    Every constraint is a declaration-level rule, the way Kubernetes expresses
    podAffinity and podAntiAffinity through label selectors (#26).

    Example:
        >>> sorted(generate_workloads())
        ['namespaces']
    """
    namespaces: dict[str, list[dict]] = {}
    for svc_def in SERVICES:
        namespaces.setdefault(svc_def[1], []).append(_declaration(svc_def))

    declarations = {decl["name"]: decl for decls in namespaces.values() for decl in decls}
    _apply_anti_affinity_spread(declarations)
    _apply_affinity_chains(declarations)
    _apply_cross_anti_affinity(declarations)
    return {"namespaces": namespaces}


def _declaration(svc_def: tuple) -> dict:
    """One service as an IR v1 declaration, before any affinity rule."""
    entry = {
        "name": svc_def[0],
        "replicas": svc_def[2],
        "requests": _resources(*svc_def[3:11]),
    }
    if svc_def[11]:
        entry["nodeSelector"] = svc_def[11]
    if svc_def[13]:
        entry["topologySpread"] = {"maxSkew": 1, "topologyKey": svc_def[13]}
    return entry


def _service_key(name: str) -> str:
    """The `namespace/name` target that names every replica of a service."""
    namespace = next(svc[1] for svc in SERVICES if svc[0] == name)
    return f"{namespace}/{name}"


def _apply_anti_affinity_spread(declarations: dict[str, dict]) -> None:
    """Spread services repel their own replicas: at most one replica per node.

    WHY: this forces the GA to spread pods across nodes. Column 12 is the spread
    flag. An earlier version filtered on column 7, the disk-read rate, which is
    non-zero for every service, so all 49 services were spread.
    """
    for svc in SERVICES:
        if svc[12]:
            declarations[svc[0]].setdefault("antiAffinity", []).append(_service_key(svc[0]))


def _apply_affinity_chains(declarations: dict[str, dict]) -> None:
    """Link services in affinity chains: each pod of A wants a pod of B on its node.

    WHY: chains create cascading co-location pressure. An earlier version paired
    replica i of A with replica i of B; Kubernetes cannot express that, so each link
    is now a declaration-level rule satisfied by any one replica of the next service.
    """
    for chain in AFFINITY_CHAINS:
        for src, dst in zip(chain, chain[1:]):
            declarations[src].setdefault("affinity", []).append(_service_key(dst))


def _apply_cross_anti_affinity(declarations: dict[str, dict]) -> None:
    """Cross-tier anti-affinity: no pod of A shares a node with a pod of B.

    WHY: prevents the GA from simply partitioning workloads by tier.
    """
    for svc_a, svc_b in ANTI_AFFINITY_CROSS:
        declarations[svc_a].setdefault("antiAffinity", []).append(_service_key(svc_b))


def compute_resource_summary(infra: dict, workloads: dict) -> None:
    """Print resource utilization analysis for verification."""
    # Node capacity
    total_cpu = sum(n["allocatable"]["cpu"] for n in infra["nodes"])
    total_ram = sum(n["allocatable"]["ram"] for n in infra["nodes"])
    total_gpu = sum(n["allocatable"]["gpu"] for n in infra["nodes"])

    # DaemonSet overhead
    ds_cpu = sum(d["resources"]["cpu"] for d in infra["daemonsets"])
    ds_ram = sum(d["resources"]["ram"] for d in infra["daemonsets"])
    overhead_cpu = ds_cpu * len(infra["nodes"])
    overhead_ram = ds_ram * len(infra["nodes"])

    net_cpu = total_cpu - overhead_cpu
    net_ram = total_ram - overhead_ram

    # Pod requests
    pod_cpu = sum(p["requests"]["cpu"] for ns in workloads.get("namespaces", {}).values() for p in ns for _ in range(p["replicas"]))
    pod_ram = sum(p["requests"]["ram"] for ns in workloads.get("namespaces", {}).values() for p in ns for _ in range(p["replicas"]))
    pod_gpu = sum(p["requests"]["gpu"] for ns in workloads.get("namespaces", {}).values() for p in ns for _ in range(p["replicas"]))

    fill_cpu = pod_cpu / net_cpu * 100
    fill_ram = pod_ram / net_ram * 100
    fill_gpu = pod_gpu / total_gpu * 100 if total_gpu > 0 else 0

    total_pods = sum(p.get("replicas", 1) for ns in workloads.get("namespaces", {}).values() for p in ns)
    total_nodes = len(infra["nodes"])

    decls = [d for ns in workloads["namespaces"].values() for d in ns]
    anti_aff_count = sum(len(d.get("antiAffinity", [])) for d in decls)
    aff_count = sum(len(d.get("affinity", [])) for d in decls)

    print(f"{'═' * 60}")
    print(f"  MSC IRINA SCALE — Resource Summary")
    print(f"{'═' * 60}")
    print(f"  Nodes:          {total_nodes}")
    print(f"  Pods:           {total_pods}")
    print(f"  Rules:          {anti_aff_count} anti-affinity + {aff_count} affinity (declaration level)")
    print(f"{'─' * 60}")
    print(f"  Cluster CPU:    {total_cpu:.0f} cores (net: {net_cpu:.1f})")
    print(f"  Cluster RAM:    {total_ram:.0f} GiB  (net: {net_ram:.1f})")
    print(f"  Cluster GPU:    {total_gpu:.0f} units")
    print(f"{'─' * 60}")
    print(f"  Pod CPU demand: {pod_cpu:.0f} cores  ({fill_cpu:.1f}% fill)")
    print(f"  Pod RAM demand: {pod_ram:.0f} GiB   ({fill_ram:.1f}% fill)")
    print(f"  Pod GPU demand: {pod_gpu:.0f} units  ({fill_gpu:.1f}% fill)")
    print(f"{'═' * 60}\n")


def main() -> None:
    """Generate and write the MSC Irina test data files."""
    infra = generate_infra()
    workloads = generate_workloads()

    compute_resource_summary(infra, workloads)

    infra_path = "testdata/irina_infra.yaml"
    workloads_path = "testdata/irina_workloads.yaml"

    with open(infra_path, "w") as f:
        f.write(_infra_header(infra))
        yaml.dump(infra, f, default_flow_style=False, sort_keys=False,
                  allow_unicode=True, width=120)

    with open(workloads_path, "w") as f:
        f.write(_workloads_header(workloads))
        yaml.dump(workloads, f, default_flow_style=False, sort_keys=False,
                  allow_unicode=True, width=120)

    print(f"  Written: {infra_path}")
    print(f"  Written: {workloads_path}")


if __name__ == "__main__":
    main()
